namespace Escape.Core
{
    /// <summary>
    /// 폐병원의 방 이름. 방 번호는 j * 3 + i (TowerLayout 평면도 참고):
    /// 0=남서, 1=남쪽 가운데(정문 쪽), 2=남동, 3=서쪽 계단 홀, 4=중앙 복도, 5=동쪽 계단 홀, 6=북서, 7=북쪽 가운데, 8=북동.
    /// 지도 옆에 지금 있는 방의 이름을 보여 주는 데 쓴다.
    /// </summary>
    public static class RoomNames
    {
        // [층][방]
        static readonly string[][] Names =
        {
            // 지하2
            new[] { "세탁실", "기계실", "창고", "서쪽 계단 홀", "지하 복도", "동쪽 계단 홀", "폐기물실", "승강기 앞 기계실", "비품실" },
            // 지하1
            new[] { "영안실", "방사선실", "약품 창고", "서쪽 계단 홀", "지하 복도", "동쪽 계단 홀", "격리실", "승강기 앞 대기실", "소독실" },
            // 1층
            new[] { "약국", "정문 로비", "응급실", "서쪽 계단 홀", "중앙 복도", "동쪽 계단 홀", "원무과", "상담실", "접수실" },
            // 2층
            new[] { "처치실", "주사실", "병실 201", "서쪽 계단 홀", "병동 복도", "동쪽 계단 홀", "간호사실", "병실 202", "병실 203" },
            // 3층
            new[] { "병실 301", "병실 302", "수술 준비실", "서쪽 계단 홀", "병동 복도", "동쪽 계단 홀", "병실 303", "VIP 병실", "병실 304" },
        };

        public static string Get(int floor, int room)
        {
            if (floor < 0 || floor >= Names.Length || room < 0 || room >= Names[floor].Length) return "";
            return Names[floor][room];
        }
    }
}
