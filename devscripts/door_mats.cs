using UnityEngine; using System.Linq; using System.Reflection; using Escape.Player; using Escape.Interaction;
string want = System.IO.File.ReadAllText("C:/Projects/Escape/devscripts/prop.txt").Trim();
var all = Door.All.Where(x => x.transform.Find("Leaf") != null).ToList();
var stat = all.GroupBy(d => string.Join("|", d.transform.Find("Leaf").GetComponent<Renderer>().sharedMaterials.Select(m => m.name.Replace("Door_","").Split('_')[0]))).OrderByDescending(g => g.Count()).Take(8).Select(g => g.Key + ":" + g.Count());
var d = all.FirstOrDefault(x => x.name.StartsWith("NormalDoor_1F") && x.transform.Find("Leaf").GetComponent<Renderer>().sharedMaterials.Any(m => m.name.Contains(want)));
if (d == null) return "no door with " + want + " | " + string.Join(", ", stat);
var leaf = d.transform.Find("Leaf"); bool alongX = leaf.localScale.x > leaf.localScale.z;
Vector3 n = alongX ? Vector3.forward : Vector3.right;
var ms = leaf.GetComponent<Renderer>().sharedMaterials; int wi = ms[0].name.Contains(want) ? 0 : 1; if (wi == 1) n = -n;
var p = Object.FindAnyObjectByType<PlayerController>();
Vector3 stand = d.transform.position + n * 2.4f; stand.y = d.transform.position.y + 0.05f;
p.Teleport(stand, Quaternion.LookRotation(-n).eulerAngles.y);
typeof(PlayerController).GetField("pitch", BindingFlags.Instance | BindingFlags.NonPublic).SetValue(p, 0f);
return d.name + " mats=" + ms[0].name + "/" + ms[1].name + " | " + string.Join(", ", stat);
