using UnityEngine; using System.Linq; using System.Reflection; using Escape.Player; using Escape.Interaction;
string want = System.IO.File.ReadAllText("C:/Projects/Escape/devscripts/prop.txt").Trim();
var h = Object.FindObjectsByType<HidingSpot>(FindObjectsInactive.Include).Where(x => x.name.StartsWith(want) && x.name.EndsWith("_1F")).FirstOrDefault();
if (h == null) return "none " + want;
var p = Object.FindAnyObjectByType<PlayerController>();
var fwd = h.transform.Find("ExitPoint").position - h.transform.Find("HidePoint").position; fwd.y = 0; fwd.Normalize();
Vector3 stand = h.transform.position + fwd * 2.4f; stand.y = h.transform.position.y + 0.1f;
p.Teleport(stand, Quaternion.LookRotation(-fwd).eulerAngles.y);
typeof(PlayerController).GetField("pitch", BindingFlags.Instance | BindingFlags.NonPublic).SetValue(p, 12f);
return h.name + " " + h.transform.position + " prompt=" + h.GetPrompt(null);
