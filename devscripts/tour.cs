using UnityEngine; using System.Reflection; using Escape.Player; using Escape.Core;
string[] a = System.IO.File.ReadAllText("C:/Projects/Escape/devscripts/prop.txt").Trim().Split(' ');
int f = int.Parse(a[0]), room = int.Parse(a[1]); int corner = a.Length > 2 ? int.Parse(a[2]) : 0;
var r = TowerLayout.RoomRect(room);
float cx = corner % 2 == 0 ? r.xMin + 1.1f : r.xMax - 1.1f, cz = corner / 2 == 0 ? r.yMin + 1.1f : r.yMax - 1.1f;
var p = Object.FindAnyObjectByType<PlayerController>();
Vector3 look = new Vector3(r.center.x - cx, 0, r.center.y - cz);
p.Teleport(new Vector3(cx, TowerLayout.FloorY(f) + 0.1f, cz), Quaternion.LookRotation(look).eulerAngles.y);
typeof(PlayerController).GetField("pitch", BindingFlags.Instance | BindingFlags.NonPublic).SetValue(p, 8f);
return $"{TowerLayout.Label(f)} {RoomThemes.Get(f, room).name} 방{room} floorTex={RoomThemes.Get(f, room).floorTex} wallTex={RoomThemes.Get(f, room).wallTex}";
