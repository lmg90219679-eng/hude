using UnityEngine; using System.Linq; using System.Reflection; using Escape.Player; using Escape.Core;
string name = System.IO.File.ReadAllText("C:/Projects/Escape/devscripts/prop.txt").Trim();
var t = GameObject.Find("Tower/HospitalProps").transform.Cast<Transform>().FirstOrDefault(x => x.name.StartsWith(name));
if (t == null) return "없음 " + name;
var p = Object.FindAnyObjectByType<PlayerController>();
Vector3 target = t.position; int room = TowerLayout.RoomAt(target);
Vector3 center = TowerLayout.RoomCenter(TowerLayout.FloorOf(target.y), room);
Vector3 dir = (center - target); dir.y = 0; if (dir.magnitude < 0.5f) dir = Vector3.forward; dir.Normalize();
Vector3 stand = target + dir * 2.6f; stand.y = target.y + 0.1f;
Vector3 look = target - stand; look.y = 0;
p.Teleport(stand, Quaternion.LookRotation(look).eulerAngles.y);
typeof(PlayerController).GetField("pitch", BindingFlags.Instance | BindingFlags.NonPublic).SetValue(p, 10f);
return $"{t.name} at {target} 방 {RoomThemes.Get(TowerLayout.FloorOf(target.y), room).name}";
